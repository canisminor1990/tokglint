use std::collections::{BTreeMap, BTreeSet};
use std::fs;
use std::path::{Path, PathBuf};

pub fn build_widget_assets() {
    build_locales();
    build_themes();
}

fn build_themes() {
    let output_dir = PathBuf::from(std::env::var_os("OUT_DIR").expect("OUT_DIR was not set"));
    for name in [
        "classic-usage-widget.json",
        "compact-fluent-quad.json",
        "classic-vertical.json",
        "minecraft-codex.json",
    ] {
        let path = Path::new("src/engine/themes").join(name);
        println!("cargo:rerun-if-changed={}", path.display());
        let source = fs::read(&path)
            .unwrap_or_else(|error| panic!("Failed to read {}: {error}", path.display()));
        let theme: serde_json::Value = serde_json::from_slice(&source)
            .unwrap_or_else(|error| panic!("Invalid theme file {}: {error}", path.display()));
        let minified = serde_json::to_vec(&theme)
            .unwrap_or_else(|error| panic!("Failed to minify {}: {error}", path.display()));
        let output = output_dir.join(name);
        write_if_changed(&output, &minified)
            .unwrap_or_else(|error| panic!("Failed to write {}: {error}", output.display()));
    }
}

struct LocaleSource {
    path: PathBuf,
    order: usize,
    code: String,
    native_name: String,
    locale_patterns: Vec<String>,
    update_via_winget: String,
    windows_font: Option<(String, String)>,
    strings: BTreeMap<String, String>,
    translations: BTreeMap<String, String>,
}

fn build_locales() {
    let locale_dir = Path::new("../locales");
    let meta_path = locale_dir.join("meta.json");
    let mut locales = read_meta(&meta_path)
        .into_iter()
        .map(|(id, meta)| read_locale(&locale_dir.join(id).join("common.json"), meta))
        .collect::<Vec<_>>();
    assert!(!locales.is_empty(), "No locale files found");
    locales.sort_by_key(|locale| locale.order);
    validate_locales(&locales);

    let english_index = locales
        .iter()
        .position(|locale| locale.code.eq_ignore_ascii_case("en"))
        .expect("An English locale with code 'en' is required");
    let mut generated = String::new();
    generated.push_str("// Generated by build.rs from ../locales/<locale>/common.json.\n");
    generated.push_str(&format!(
        "pub(super) const LANGUAGE_COUNT: usize = {};\n",
        locales.len()
    ));
    generated.push_str(&format!(
        "pub(super) const ENGLISH_INDEX: usize = {english_index};\n"
    ));
    generated.push_str("pub(super) const LANGUAGE_IDS: [LanguageId; LANGUAGE_COUNT] = [");
    for index in 0..locales.len() {
        generated.push_str(&format!("LanguageId({index}),"));
    }
    generated.push_str("];\n");
    generated.push_str("pub(super) static LOCALES: [Locale; LANGUAGE_COUNT] = [\n");
    for locale in &locales {
        generated.push_str("Locale {\n");
        generated.push_str(&format!("code: {:?},\n", locale.code));
        generated.push_str(&format!("native_name: {:?},\n", locale.native_name));
        generated.push_str("locale_patterns: &[");
        for pattern in &locale.locale_patterns {
            generated.push_str(&format!("{pattern:?},"));
        }
        generated.push_str("],\n");
        match &locale.windows_font {
            Some((name, file)) => {
                generated.push_str(&format!("windows_font: Some(({name:?}, {file:?})),\n"));
            }
            None => generated.push_str("windows_font: None,\n"),
        }
        generated.push_str(&format!(
            "update_via_winget_label: {:?},\n",
            locale.update_via_winget
        ));
        generated.push_str("strings: Strings {\n");
        for (field, value) in &locale.strings {
            generated.push_str(&format!("{field}: {value:?},\n"));
        }
        generated.push_str("},\ntranslations: &[");
        for (key, value) in &locale.translations {
            generated.push_str(&format!("({key:?}, {value:?}),"));
        }
        generated.push_str("],\n},\n");
    }
    generated.push_str("];\n");

    let output =
        PathBuf::from(std::env::var_os("OUT_DIR").expect("OUT_DIR was not set")).join("locales.rs");
    write_if_changed(&output, generated.as_bytes())
        .unwrap_or_else(|error| panic!("Failed to write {}: {error}", output.display()));
    println!("cargo:rerun-if-changed={}", locale_dir.display());
    println!("cargo:rerun-if-changed={}", meta_path.display());
}

struct LocaleMeta {
    order: usize,
    code: String,
    native_name: String,
    locale_patterns: Vec<String>,
    windows_font: Option<(String, String)>,
}

fn read_meta(path: &Path) -> Vec<(String, LocaleMeta)> {
    let value = read_json(path);
    let table = required_object(&value, path);
    let mut entries = Vec::new();
    for (id, value) in table {
        let object = value.as_object().unwrap_or_else(|| {
            panic!(
                "Locale metadata {id:?} in {} must be an object",
                path.display()
            )
        });
        let allowed = [
            "code",
            "nativeName",
            "localePatterns",
            "order",
            "windowsFontName",
            "windowsFontFile",
        ];
        for key in object.keys() {
            assert!(
                allowed.contains(&key.as_str()),
                "Unknown locale metadata key {key:?} for {id} in {}",
                path.display()
            );
        }
        let font_name = optional_json_string(object, "windowsFontName", path);
        let font_file = optional_json_string(object, "windowsFontFile", path);
        assert_eq!(
            font_name.is_some(),
            font_file.is_some(),
            "{id} in {} must define both windowsFontName and windowsFontFile",
            path.display()
        );
        let order = required_json_integer(object, "order", path);
        assert!(
            order >= 0,
            "Locale order cannot be negative for {id} in {}",
            path.display()
        );
        entries.push((
            id.clone(),
            LocaleMeta {
                order: order as usize,
                code: required_json_string(object, "code", path),
                native_name: required_json_string(object, "nativeName", path),
                locale_patterns: required_json_string_array(object, "localePatterns", path),
                windows_font: font_name.zip(font_file),
            },
        ));
    }
    entries
}

fn read_locale(path: &Path, meta: LocaleMeta) -> LocaleSource {
    let value = read_json(path);
    let table = required_object(&value, path);
    let allowed = ["update_via_winget", "strings", "translations"];
    for key in table.keys() {
        assert!(
            allowed.contains(&key.as_str()),
            "Unknown top-level locale key {key:?} in {}",
            path.display()
        );
    }

    LocaleSource {
        path: path.to_path_buf(),
        order: meta.order,
        code: meta.code,
        native_name: meta.native_name,
        locale_patterns: meta.locale_patterns,
        update_via_winget: required_json_string(table, "update_via_winget", path),
        windows_font: meta.windows_font,
        strings: required_json_string_map(table, "strings", path),
        translations: required_json_string_map(table, "translations", path),
    }
}

fn validate_locales(locales: &[LocaleSource]) {
    let english = locales
        .iter()
        .find(|locale| locale.code.eq_ignore_ascii_case("en"))
        .expect("An English locale with code 'en' is required");
    let string_keys = english.strings.keys().cloned().collect::<BTreeSet<_>>();
    let translation_keys = english
        .translations
        .keys()
        .cloned()
        .collect::<BTreeSet<_>>();
    let mut codes = BTreeSet::new();
    let mut orders = BTreeSet::new();
    let mut patterns = BTreeSet::new();

    for (expected_order, locale) in locales.iter().enumerate() {
        assert_eq!(
            locale.order,
            expected_order,
            "Locale orders must be unique and contiguous from zero; check {}",
            locale.path.display()
        );
        assert!(
            orders.insert(locale.order),
            "Duplicate locale order {}",
            locale.order
        );
        assert!(
            codes.insert(locale.code.to_ascii_lowercase()),
            "Duplicate locale code {}",
            locale.code
        );
        assert_eq!(
            locale.code.trim(),
            locale.code,
            "Locale code cannot have surrounding whitespace in {}",
            locale.path.display()
        );
        assert!(!locale.code.is_empty(), "Locale code cannot be empty");
        assert!(
            !locale.native_name.trim().is_empty(),
            "Locale native_name cannot be empty in {}",
            locale.path.display()
        );
        assert!(
            !locale.locale_patterns.is_empty(),
            "locale_patterns cannot be empty in {}",
            locale.path.display()
        );
        for pattern in &locale.locale_patterns {
            assert!(!pattern.is_empty(), "Locale patterns cannot be empty");
            assert_eq!(
                pattern.trim(),
                pattern,
                "Locale patterns cannot have surrounding whitespace in {}",
                locale.path.display()
            );
            assert_eq!(
                pattern,
                &pattern.to_ascii_lowercase(),
                "Locale patterns must be lowercase in {}",
                locale.path.display()
            );
            assert!(
                patterns.insert(pattern),
                "Duplicate locale pattern {pattern:?} in {}",
                locale.path.display()
            );
        }
        let normalized_code = locale.code.replace('_', "-").to_ascii_lowercase();
        assert!(
            locale.locale_patterns.iter().any(|pattern| {
                normalized_code == *pattern
                    || normalized_code
                        .strip_prefix(pattern)
                        .is_some_and(|suffix| suffix.starts_with('-'))
            }),
            "Locale code {:?} is not recognized by its patterns in {}",
            locale.code,
            locale.path.display()
        );
        let locale_string_keys = locale.strings.keys().cloned().collect::<BTreeSet<_>>();
        assert_eq!(
            locale_string_keys,
            string_keys,
            "Typed string keys differ from English in {}",
            locale.path.display()
        );
        let locale_translation_keys = locale.translations.keys().cloned().collect::<BTreeSet<_>>();
        assert_eq!(
            locale_translation_keys,
            translation_keys,
            "Translation keys differ from English in {}",
            locale.path.display()
        );
        for (key, value) in &locale.translations {
            assert!(!value.trim().is_empty(), "Empty translation for {key:?}");
            let english_value = &english.translations[key];
            assert_eq!(
                placeholders(value),
                placeholders(english_value),
                "Placeholders differ for {key:?} in {}",
                locale.path.display()
            );
        }
        for (key, value) in &locale.strings {
            assert!(!value.trim().is_empty(), "Empty typed string {key:?}");
            let english_value = &english.strings[key];
            assert_eq!(
                placeholders(value),
                placeholders(english_value),
                "Placeholders differ for typed string {key:?} in {}",
                locale.path.display()
            );
        }
    }
}

fn placeholders(value: &str) -> Vec<&str> {
    let mut placeholders = Vec::new();
    let mut remainder = value;
    while let Some(start) = remainder.find('{') {
        let candidate = &remainder[start..];
        let Some(end) = candidate.find('}') else {
            break;
        };
        placeholders.push(&candidate[..=end]);
        remainder = &candidate[end + 1..];
    }
    placeholders.sort_unstable();
    placeholders
}

fn read_json(path: &Path) -> serde_json::Value {
    let source = fs::read_to_string(path)
        .unwrap_or_else(|error| panic!("Failed to read {}: {error}", path.display()));
    let source = source.strip_prefix('\u{feff}').unwrap_or(&source);
    serde_json::from_str(source)
        .unwrap_or_else(|error| panic!("Invalid JSON {}: {error}", path.display()))
}

fn required_object<'a>(
    value: &'a serde_json::Value,
    path: &Path,
) -> &'a serde_json::Map<String, serde_json::Value> {
    value
        .as_object()
        .unwrap_or_else(|| panic!("{} must contain a JSON object", path.display()))
}

fn required_json_string(
    table: &serde_json::Map<String, serde_json::Value>,
    key: &str,
    path: &Path,
) -> String {
    table
        .get(key)
        .and_then(serde_json::Value::as_str)
        .unwrap_or_else(|| panic!("Missing string {key:?} in {}", path.display()))
        .to_owned()
}

fn optional_json_string(
    table: &serde_json::Map<String, serde_json::Value>,
    key: &str,
    path: &Path,
) -> Option<String> {
    table.get(key).map(|value| {
        value
            .as_str()
            .unwrap_or_else(|| panic!("{key:?} must be a string in {}", path.display()))
            .to_owned()
    })
}

fn required_json_integer(
    table: &serde_json::Map<String, serde_json::Value>,
    key: &str,
    path: &Path,
) -> i64 {
    table
        .get(key)
        .and_then(serde_json::Value::as_i64)
        .unwrap_or_else(|| panic!("Missing integer {key:?} in {}", path.display()))
}

fn required_json_string_array(
    table: &serde_json::Map<String, serde_json::Value>,
    key: &str,
    path: &Path,
) -> Vec<String> {
    table
        .get(key)
        .and_then(serde_json::Value::as_array)
        .unwrap_or_else(|| panic!("Missing array {key:?} in {}", path.display()))
        .iter()
        .map(|value| {
            value
                .as_str()
                .unwrap_or_else(|| panic!("{key:?} must contain strings in {}", path.display()))
                .to_owned()
        })
        .collect()
}

fn required_json_string_map(
    table: &serde_json::Map<String, serde_json::Value>,
    key: &str,
    path: &Path,
) -> BTreeMap<String, String> {
    table
        .get(key)
        .and_then(serde_json::Value::as_object)
        .unwrap_or_else(|| panic!("Missing object {key:?} in {}", path.display()))
        .iter()
        .map(|(entry_key, value)| {
            let value = value.as_str().unwrap_or_else(|| {
                panic!("{key}.{entry_key} must be a string in {}", path.display())
            });
            (entry_key.clone(), value.to_owned())
        })
        .collect()
}

fn write_if_changed(path: &Path, contents: &[u8]) -> std::io::Result<()> {
    if fs::read(path).is_ok_and(|existing| existing == contents) {
        return Ok(());
    }
    fs::write(path, contents)
}
